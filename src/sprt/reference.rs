#[test]
fn trinomial_matches_fastchess() {
    let mut worst: f32 = 0.0;
    for &(model, elo0, elo1, w, d, l, expected) in TRINOMIAL {
        let got = trinomial::get_llr(&WLD { w, l, d }, elo0, elo1, model);
        let diff = (got - expected).abs();
        worst = worst.max(diff);
        assert!(
            diff <= TOLERANCE,
            "{model:?} [{elo0}, {elo1}] w{w} d{d} l{l}: got {got}, fastchess {expected}"
        );
    }
    println!("worst trinomial difference from fastchess: {worst}");
}

#[test]
fn pentanomial_matches_fastchess() {
    let mut worst: f32 = 0.0;
    for &(model, elo0, elo1, ll, ld, wl, dd, wd, ww, expected) in PENTANOMIAL {
        let pairs = WLDPairs {
            ll,
            ld,
            wl,
            dd,
            wd,
            ww,
            ..Default::default()
        };
        let got = pentanomial::get_llr(&pairs, elo0, elo1, model);
        let diff = (got - expected).abs();
        worst = worst.max(diff);
        assert!(
            diff <= TOLERANCE,
            "{model:?} [{elo0}, {elo1}] ll{ll} ld{ld} wl{wl} dd{dd} wd{wd} ww{ww}: got {got}, fastchess {expected}"
        );
    }
    println!("worst pentanomial difference from fastchess: {worst}");
}
